package com.wangzan101.mika.core.uistate

/**
 * 危险动作词表:付款、发送、提交、删除这类点下去就收不回来的动作。
 *
 * 用途:点击前先看一眼目标文字,命中就要求用户确认一次,不让模型自己决定。
 * 这是合规和可靠性措施,不是反检测手段。
 */
object RiskyActions {
    /** 一次性不可逆的动作。宁可多问一次。 */
    private val WORDS = listOf(
        // 钱
        "付款", "支付", "确认支付", "立即支付", "去支付", "立即购买", "确认购买",
        "提交订单", "确认下单", "下单", "结算", "转账", "确认转账", "汇款", "打赏",
        // 打电话:会打扰真人,而且是点一下就打出去了
        "拨打", "呼叫", "立即通话", "拨号", "视频通话",
        // 对外发声
        "发送", "发送给", "发表", "发布", "群发", "全部发送",
        // 提交类
        "提交", "确认提交", "提交申请", "确认申报", "申报", "实名认证",
        // 破坏性
        "删除", "永久删除", "清空", "注销", "解绑", "退出登录", "解散", "撤回",
        // 社交(关注/点赞默认也问一次)
        "关注", "点赞", "收藏", "转发",
    )

    /** 命中就返回命中的那个词,没命中返回 null。 */
    fun hits(label: String?): String? {
        val t = label?.trim().orEmpty()
        if (t.isEmpty()) return null
        return WORDS.firstOrNull { t.contains(it) }
    }

    /** 给模型看的提示:说清楚为什么停下来了。 */
    fun askUser(word: String): String =
        "这一步是「$word」,点下去就收不回来了。先把要执行的内容告诉用户,等用户明确确认后再带 confirmed=true 重试这一次。不要自己决定。"
}